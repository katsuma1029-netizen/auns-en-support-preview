const html = document.documentElement;
const header = document.querySelector('.site-header');
const menuButton = document.getElementById('menuButton');
const mobileMenu = document.getElementById('mobileMenu');
const languageSwitch = document.getElementById('languageSwitch');

function updateHeaderState() {
  header.classList.toggle('scrolled', window.scrollY > 20);
}

function closeMenu() {
  menuButton.classList.remove('is-open');
  mobileMenu.classList.remove('is-open');
  document.body.classList.remove('menu-open');
  menuButton.setAttribute('aria-expanded', 'false');
  menuButton.setAttribute('aria-label', currentLanguage === 'ja' ? 'メニューを開く' : 'Open menu');
}

function toggleMenu() {
  const isOpen = menuButton.classList.toggle('is-open');
  mobileMenu.classList.toggle('is-open', isOpen);
  document.body.classList.toggle('menu-open', isOpen);
  menuButton.setAttribute('aria-expanded', String(isOpen));
  menuButton.setAttribute('aria-label', isOpen
    ? (currentLanguage === 'ja' ? 'メニューを閉じる' : 'Close menu')
    : (currentLanguage === 'ja' ? 'メニューを開く' : 'Open menu'));
}

menuButton.addEventListener('click', toggleMenu);
mobileMenu.querySelectorAll('a').forEach(link => link.addEventListener('click', closeMenu));
window.addEventListener('scroll', updateHeaderState, { passive: true });
updateHeaderState();

let currentLanguage = localStorage.getItem('auns-language') || 'ja';

function applyLanguage(language) {
  const dictionary = translations[language];
  if (!dictionary) return;

  currentLanguage = language;
  html.lang = language === 'ja' ? 'ja' : 'en';

  document.title = dictionary['meta.title'];

  const descriptionMeta = document.querySelector('meta[name="description"]');
  const ogTitleMeta = document.querySelector('meta[property="og:title"]');
  const ogDescriptionMeta = document.querySelector('meta[property="og:description"]');
  const ogLocaleMeta = document.querySelector('meta[property="og:locale"]');

  if (descriptionMeta) descriptionMeta.setAttribute('content', dictionary['meta.description']);
  if (ogTitleMeta) ogTitleMeta.setAttribute('content', dictionary['meta.title']);
  if (ogDescriptionMeta) ogDescriptionMeta.setAttribute('content', dictionary['meta.ogDescription']);
  if (ogLocaleMeta) ogLocaleMeta.setAttribute('content', language === 'ja' ? 'ja_JP' : 'en_US');

  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.dataset.i18n;
    if (dictionary[key] !== undefined) element.textContent = dictionary[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    const key = element.dataset.i18nHtml;
    if (dictionary[key] !== undefined) element.innerHTML = dictionary[key];
  });

  const currentLabel = document.querySelector('[data-lang-label="current"]');
  const nextLabel = document.querySelector('[data-lang-label="next"]');
  currentLabel.textContent = language === 'ja' ? 'JP' : 'EN';
  nextLabel.textContent = language === 'ja' ? 'EN' : 'JP';

  languageSwitch.setAttribute('aria-label', language === 'ja' ? '英語表示に切り替える' : 'Switch to Japanese');
  menuButton.setAttribute('aria-label', language === 'ja' ? 'メニューを開く' : 'Open menu');
  localStorage.setItem('auns-language', language);
}

languageSwitch.addEventListener('click', () => {
  applyLanguage(currentLanguage === 'ja' ? 'en' : 'ja');
});

applyLanguage(currentLanguage);

const revealElements = document.querySelectorAll('.reveal');

if ('IntersectionObserver' in window) {
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -6% 0px' });

  revealElements.forEach(element => observer.observe(element));
} else {
  revealElements.forEach(element => element.classList.add('is-visible'));
}
