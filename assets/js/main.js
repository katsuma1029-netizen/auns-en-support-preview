let currentLanguage = localStorage.getItem('auns-language') || 'ja';

function applyLanguage(language) {
  const dictionary = translations[language];
  if (!dictionary) return;

  currentLanguage = language;
  html.lang = language === 'ja' ? 'ja' : 'en';

  const page = document.body.dataset.page || 'home';
  const metaPrefix = page === 'privacy' ? 'privacy.meta' : 'meta';
  const pageTitle = dictionary[`${metaPrefix}.title`];
  const pageDescription = dictionary[`${metaPrefix}.description`];
  const pageOgDescription = dictionary[`${metaPrefix}.ogDescription`];

  if (pageTitle) document.title = pageTitle;

  const descriptionMeta = document.querySelector('meta[name="description"]');
  const ogTitleMeta = document.querySelector('meta[property="og:title"]');
  const ogDescriptionMeta = document.querySelector('meta[property="og:description"]');
  const ogLocaleMeta = document.querySelector('meta[property="og:locale"]');

  if (descriptionMeta && pageDescription) descriptionMeta.setAttribute('content', pageDescription);
  if (ogTitleMeta && pageTitle) ogTitleMeta.setAttribute('content', pageTitle);
  if (ogDescriptionMeta && pageOgDescription) ogDescriptionMeta.setAttribute('content', pageOgDescription);
  if (ogLocaleMeta) ogLocaleMeta.setAttribute('content', language === 'ja' ? 'ja_JP' : 'en_US');

  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.dataset.i18n;
    if (dictionary[key] !== undefined) element.textContent = dictionary[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    const key = element.dataset.i18nHtml;
    if (dictionary[key] !== undefined) element.innerHTML = dictionary[key];
  });

  const currentLabel = document.querySelector('[data-lang-label="current"]');
  const nextLabel = document.querySelector('[data-lang-label="next"]');
  currentLabel.textContent = language === 'ja' ? 'JP' : 'EN';
  nextLabel.textContent = language === 'ja' ? 'EN' : 'JP';

  languageSwitch.setAttribute('aria-label', language === 'ja' ? '英語表示に切り替える' : 'Switch to Japanese');
  menuButton.setAttribute('aria-label', language === 'ja' ? 'メニューを開く' : 'Open menu');
  localStorage.setItem('auns-language', language);
}

languageSwitch.addEventListener('click', () => {
  applyLanguage(currentLanguage === 'ja' ? 'en' : 'ja');
});

applyLanguage(currentLanguage);

